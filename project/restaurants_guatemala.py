def _generate_catalog() -> list[dict]:
    random.seed(42)
    items = _seed_restaurants()
    used_names = {r["nombre"] for r in items}
    idx = 1
    while len(items) < 214:
        rid = "gt%03d" % idx
        idx += 1
        if rid in {r["id"] for r in items}:
            continue
        nombre = KNOWN[(idx - 2) % len(KNOWN)]
        if nombre in used_names:
            nombre = "%s %s" % (nombre, _SUFFIXES[(idx - 2) % len(_SUFFIXES)])
        used_names.add(nombre)
        zona = ZONAS[(idx - 2) % len(ZONAS)]
        cocina = CUISINES[(idx - 2) % len(CUISINES)]
        ambiente = AMBIENTES[(idx - 2) % len(AMBIENTES)]
        rating = round(random.uniform(3.8, 4.9), 1)
        precio = int(random.uniform(40, 2000) // 5 * 5)
        prefs = _build_prefs(cocina, ambiente, precio, rating)
        items.append(
            {
                "id": rid,
                "nombre": nombre,
                "zona": zona,
                "rating": rating,
                "precio": precio,
                "cocina": cocina,
                "ambiente": ambiente,
                "prefs": prefs,
            }
        )
    return items


