def _cuisine_prefs(cocina: str) -> dict[str, float]:
    base: dict[str, float] = {"equilibrado": 0.55}
    mapping = {
        "Japonesa": {"pref_japonesa": 1.0, "sabor_umami": 0.85, "gourmet": 0.7},
        "Italiana": {"pref_italiana": 1.0, "slow_food": 0.65, "romantic": 0.5},
        "Guatemalteca": {"pref_guatemalteca": 1.0, "tradicional": 0.8, "contundente": 0.75},
        "Mexicana": {"street_food": 0.7, "sabor_picante": 0.75},
        "Peruana": {"explorador": 0.65, "sabor_fresco": 0.7},
        "Mariscos": {"gourmet": 0.6, "sabor_fresco": 0.8},
        "Steakhouse": {"contundente": 0.9, "premium": 0.75, "smoky": 0.7},
        "Cafe": {"brunch": 0.85, "casual": 0.7, "aesthetic": 0.6},
    }
    base.update(mapping.get(cocina, {"moderno": 0.5}))
    return base


def _ambiente_prefs(ambiente: str) -> dict[str, float]:
    mapping = {
        "casual": {"casual": 0.9, "fast_service": 0.6},
        "elegante": {"elegant": 0.9, "gourmet": 0.7, "exclusive": 0.55},
        "romantico": {"romantic": 0.95, "slow_food": 0.6},
        "familiar": {"family_friendly": 0.95, "comfort_food": 0.7},
        "trendy": {"trendy": 0.9, "aesthetic": 0.75, "nightlife": 0.4},
        "tranquilo": {"tranquil": 0.9, "slow_food": 0.55},
        "nocturno": {"nightlife": 0.9, "social_grupo": 0.65},
        "brunch": {"brunch": 0.95, "aesthetic": 0.5},
    }
    return mapping.get(ambiente, {"casual": 0.5})


def _build_prefs(cocina: str, ambiente: str, precio: int, rating: float) -> dict[str, float]:
    prefs = _cuisine_prefs(cocina)
    for k, v in _ambiente_prefs(ambiente).items():
        prefs[k] = max(prefs.get(k, 0.0), v)
    if precio >= 350:
        prefs["premium"] = max(prefs.get("premium", 0.0), 0.85)
        prefs["exclusive"] = max(prefs.get("exclusive", 0.0), 0.7)
    elif precio <= 80:
        prefs["ahorrador"] = max(prefs.get("ahorrador", 0.0), 0.8)
    if rating >= 4.6:
        prefs["gourmet"] = max(prefs.get("gourmet", 0.0), 0.75)
    extra = random.sample(_PREF_POOL, k=3)
    for p in extra:
        prefs[p] = max(prefs.get(p, 0.0), round(random.uniform(0.35, 0.75), 2))
    return {k: round(min(1.0, v), 2) for k, v in prefs.items()}


